    -- Consent decision and its audit event commit or roll back together.
    create or replace function public.signoff_consent_with_audit(
        p_consent_id bigint,
        p_actor_id text,
        p_actor_email text,
        p_decision text,
        p_request_id text default null
    ) returns boolean
    language plpgsql
    security definer
    set search_path = public
    as $$
    declare
        affected integer;
    begin
        if p_decision not in ('approve', 'reject') then
            raise exception 'Invalid consent decision';
        end if;

        update public.consent_submissions
        set status = case when p_decision = 'approve' then 'signed_off' else 'rejected' end,
            signed_off_by = p_actor_email,
            signed_off_at = now()
        where id = p_consent_id and status = 'pending';

        get diagnostics affected = row_count;
        if affected = 0 then
            return false;
        end if;

        insert into public.audit_events (
            actor_id, action, resource_type, resource_id, outcome, request_id
        ) values (
            p_actor_id, 'consent.' || p_decision, 'consent_submission',
            p_consent_id::text, 'success', p_request_id
        );
        return true;
    end;
    $$;

